def generate_report(report_type: str) -> Path:
    """Route to the appropriate report generator."""
    generators = {
        "master": generate_master_report,
        "sec": generate_sec_bundle,
        "doj": generate_doj_referral,
        "leg": generate_legislative_brief,
        "legislative": generate_legislative_brief,
    }

    gen = generators.get(report_type.lower())
    if not gen:
        raise ValueError(f"Unknown report type: {report_type}. "
                         f"Available: {', '.join(generators.keys())}")

    output_path = gen()
    print(f"\n  ✓ Report generated: {output_path}")
    return output_path


def main():
    parser = argparse.ArgumentParser(description="JLAW Report Generator Agent")
    parser.add_argument("--type", type=str, required=True,
                        choices=["master", "sec", "doj", "leg", "legislative"],
                        help="Report type to generate")

    args = parser.parse_args()

    print(f"\n{'='*60}")
    print(f"  JLAW REPORT GENERATOR — {args.type.upper()}")
    print(f"  Started: {datetime.now().isoformat()}")
    print(f"{'='*60}\n")

    output = generate_report(args.type)

    print(f"\n{'='*60}")
    print(f"  REPORT GENERATION COMPLETE")
    print(f"  Output: {output}")
    print(f"  Size: {output.stat().st_size / 1024:.1f} KB")
    print(f"{'='*60}\n")


if __name__ == "__main__":
    main()
