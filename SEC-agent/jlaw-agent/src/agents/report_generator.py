def load_anomaly_db() -> Dict:
    """Load the anomaly database."""
    db_path = ANOMALY_DIR / "anomaly_database.json"
    if db_path.exists():
        with open(db_path) as f:
            return json.load(f)
    return {"anomalies": [], "patterns": []}


def load_deliverable_inventory() -> Dict:
    """Load the parsed deliverable inventory."""
    inv_path = PARSED_DIR / "deliverables" / "deliverable_inventory.json"
    if inv_path.exists():
        with open(inv_path) as f:
            return json.load(f)
    return {}


def add_title_page(doc: Document, title: str, subtitle: str, date: str,
                   classification: str = "PRIVILEGED & CONFIDENTIAL"):
    """Add a formatted title page to the document."""
    # Classification header
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(classification)
    run.bold = True
    run.font.size = Pt(10)
    run.font.color.rgb = RGBColor(192, 0, 0)

    for _ in range(4):
        doc.add_paragraph()

    # Title
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(title)
    run.bold = True
    run.font.size = Pt(24)

    doc.add_paragraph()

    # Subtitle
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(subtitle)
    run.font.size = Pt(14)
    run.font.color.rgb = RGBColor(89, 89, 89)

    for _ in range(3):
        doc.add_paragraph()

    # Meta info
    meta_lines = [
        f"Date: {date}",
        "Subject: Nike, Inc. (NKE) | CIK 0000320187",
        "Scope: FY2019 through Q1 CY2026",
        "Generated by: JLAW Agent Platform v5.0",
    ]
    for line in meta_lines:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(line)
        run.font.size = Pt(11)
        run.font.color.rgb = RGBColor(89, 89, 89)

    doc.add_page_break()


def add_anomaly_table(doc: Document, anomalies: List[Dict], title: str = "Anomaly Summary"):
    """Add a table summarizing anomalies."""
    doc.add_heading(title, level=2)

    if not anomalies:
        doc.add_paragraph("No anomalies found in this category.")
        return

    table = doc.add_table(rows=1, cols=5)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER

    # Headers
    headers = ["ID", "Severity", "Fiscal Year", "Category", "Title"]
    for i, header in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = header
        for paragraph in cell.paragraphs:
            for run in paragraph.runs:
                run.bold = True
                run.font.size = Pt(9)

    # Data rows
    for anomaly in anomalies:
        row = table.add_row()
        values = [
            anomaly.get("anomaly_id", ""),
            anomaly.get("severity", ""),
            anomaly.get("fiscal_year", ""),
            anomaly.get("category", ""),
            anomaly.get("title", "")[:80],
        ]
        for i, val in enumerate(values):
            row.cells[i].text = str(val)
            for paragraph in row.cells[i].paragraphs:
                for run in paragraph.runs:
                    run.font.size = Pt(8)

    doc.add_paragraph()


def add_pattern_section(doc: Document, patterns: List[Dict], anomalies: List[Dict]):
    """Add compounding pattern analysis section."""
    doc.add_heading("Compounding Patterns", level=1)

    if not patterns:
        doc.add_paragraph("No compounding patterns identified.")
        return

    for pattern in patterns:
        doc.add_heading(f"{pattern['pattern_id']}: {pattern['title']}", level=2)
        doc.add_paragraph(pattern.get("description", ""))

        # List linked anomalies
        linked = [a for a in anomalies if a["anomaly_id"] in pattern.get("anomaly_ids", [])]
        if linked:
            doc.add_paragraph(
                f"Years spanned: {', '.join(pattern.get('years_spanned', []))}",
            )
            doc.add_paragraph(f"Linked anomalies: {len(linked)}")
            for a in linked:
                doc.add_paragraph(
                    f"  • {a['anomaly_id']}: {a['title']}",
                    style="List Bullet",
                )

        doc.add_paragraph()


